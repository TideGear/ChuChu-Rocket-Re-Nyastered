"""Inventory of every Ninja chunk model in the user's 1ST_READ.BIN: size, strips, texture slots, the object nodes that use it, the tables that list those nodes and the functions
that reference the tables or nodes (and their callers). usage: dc_mesh_inventory.py <1ST_READ.BIN> <functions.txt> > docs/dreamcast_meshes.md"""
import struct, sys, bisect, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dc_models as M
B = 0x8C010000
d = open(sys.argv[1], 'rb').read()
funcs = sorted(int(l.split()[0], 16) for l in open(sys.argv[2]))
fn = lambda a: funcs[bisect.bisect_right(funcs, a) - 1]
ptr = {}
for i in range(0, len(d) - 3, 4):
    v = struct.unpack_from('<I', d, i)[0]
    if B <= v < B + len(d): ptr.setdefault(v, []).append(B + i)
CODE_END = 0x8C010000 + 0x75000     # the code and literal pools end before the model data begins
bsr = {}
for i in range(0, len(d) - 1, 2):
    op = struct.unpack_from('<H', d, i)[0]
    if op & 0xF000 == 0xB000:
        disp = op & 0xFFF; disp = disp - 4096 if disp & 0x800 else disp
        bsr.setdefault(B + i + 4 + 2 * disp, []).append(B + i)
def code_refs(a):
    """functions whose literal pool or bsr targets reference address a"""
    out = set()
    for h in ptr.get(a, []):
        if h < CODE_END: out.add(fn(h))
    for h in bsr.get(a, []): out.add(fn(h))
    return sorted(out)
def callers(f, depth=2):
    chain = []; cur = [f]
    for _ in range(depth):
        nxt = set()
        for x in cur:
            for h in ptr.get(x, []):
                if h < CODE_END: nxt.add(fn(h))
                else: nxt.add(h)           # a data table listing the function (task table)
            for h in bsr.get(x, []): nxt.add(fn(h))
        nxt.discard(f); chain.append(sorted(nxt)); cur = [x for x in nxt if x < CODE_END]
    return chain
def holders(a, depth=3):
    """data words (tables, nodes) that point at a, and what points at those"""
    res = []
    for h in ptr.get(a, []):
        if h >= CODE_END: res.append(h)
    return res
models = M.find_models(d, B)
print('# Dreamcast mesh inventory (generated by tools/dc_mesh_inventory.py)\n')
print('One row per Ninja chunk model found in `1ST_READ.BIN`: address, vertices, strips, size in model units, texture slots, then what refers to it. `node` = an object node (word before the model pointer); `table` = a data word that points at the node or model; `code` = functions whose literal pool references it.\n')
print('| model | verts | strips | size x y z | tex slots | node(s) | referenced by (table words) | code refs |\n|---|---|---|---|---|---|---|---|')
for (o, vo, po, vl, pl) in sorted(models, key=lambda m: m[0]):
    a = B + o
    xs = [v[0][0] for v in vl.values()]; ys = [v[0][1] for v in vl.values()]; zs = [v[0][2] for v in vl.values()]
    texs = sorted(set(t for _, _, t, _ in pl if t is not None))
    nodes = [h - 4 for h in ptr.get(a, []) if h >= CODE_END]
    tbl = []
    for n in nodes:
        for h in ptr.get(n, []): tbl.append(h)
    cr = code_refs(a) + [f for n in nodes for f in code_refs(n)] + [fn(h) for t in tbl if t < CODE_END for h in [t]]
    tr = [hex(t) for t in tbl if t >= CODE_END]
    print('| %s | %d | %d | %.1f x %.1f x %.1f | %s | %s | %s | %s |' % (hex(a), len(vl), len(pl), max(xs) - min(xs), max(ys) - min(ys), max(zs) - min(zs), ','.join(str(t & 0xfff) for t in texs[:6]),
          ' '.join(hex(n) for n in nodes[:3]), ' '.join(tr[:4]), ' '.join(sorted(set(hex(c) for c in cr))[:4])))
