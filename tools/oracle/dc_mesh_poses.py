"""Fit every Dreamcast mesh against every real Flycast frame (tools/oracle/dc_fit.py) and print, per model, how it is drawn: scale, rotation (tilt about X, yaw about Y), height and the
residual. usage: dc_mesh_poses.py <state files...> > docs/dreamcast_mesh_poses.md"""
import sys, os, math, glob, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
import numpy as np, dc_models as M, ta_parse as t, dc_fit as F
B = 0x8c010000
d = open('local/cache/assets/dreamcast/files/1ST_READ.BIN', 'rb').read()
models = M.find_models(d, B)
cands = []     # (model address, group index, verts, uvs, positions)
for (o, vo, po, vl, pl) in models:
    g = []
    for s, rev, tex, mat in pl:
        if g and g[-1][0] == tex: g[-1][1] += list(s)
        else: g.append([tex, list(s)])
    for gi, (tex, flat) in enumerate(g):
        if len(flat) < 3: continue
        cands.append((B + o, gi, np.array([(u, v) for i, u, v in flat]), np.array([vl[i][0] for i, u, v in flat]), np.array([vl[i][1] if vl[i][1] else (0.0, 0.0, 0.0) for i, u, v in flat]), all(vl[i][1] for i, u, v in flat)))
bylen = collections.defaultdict(list)
for c in cands: bylen[len(c[2])].append(c)
stats = collections.defaultdict(list)
for path in sys.argv[1:]:
    st = open(path, 'rb').read()
    regions = ((0x253e10, 0x2c0000, 'opaque'), (0x1900003, 0x1b00000, 'second list'))
    polys = [(p, ln) for lo, hi, ln in regions for p in t.parse(st, lo, hi)]
    for p, listname in polys:
        if not p['strips']: continue
        sv = [v for s in p['strips'] for v in s]
        if len(sv) not in bylen: continue
        uvs = np.array([F.uv_of(p, v) for v in sv])
        best = None
        for (addr, gi, muv, mpos, mnrm, hasn) in bylen[len(sv)]:
            if np.abs(muv - uvs).max() > 0.004: continue
            dst = np.array([F.unproject(v[1], v[2], v[3]) for v in sv])
            if np.ptp(mpos, axis=0).min() < 1e-6 and np.linalg.matrix_rank(mpos - mpos.mean(0), tol=1e-6) < 2: continue
            try: s_, R, t_ = F.umeyama(mpos, dst)
            except Exception: continue
            res = np.linalg.norm((s_ * (R @ mpos.T)).T + t_ - dst, axis=1); rms = math.sqrt((res ** 2).mean())
            if rms < 0.02 and (best is None or rms < best[0]): best = (rms, addr, gi, s_, R, t_, mnrm, hasn, np.array([v[6] for v in sv]), listname)
        if best:
            rms, addr, gi, s_, R, t_, mnrm, hasn, real, lname = best
            lighterr = lightL = None
            if hasn:
                n2 = (R @ mnrm.T).T; m = real > 0.305
                if m.sum() >= 3:
                    L, *_ = np.linalg.lstsq(n2[m], real[m] - 0.3, rcond=None); lightL = L; lighterr = float(np.abs(0.3 + np.maximum(0, n2 @ L) - real).max())
            a = math.degrees(math.atan2(R[2, 1], R[1, 1])); b = math.degrees(math.atan2(R[0, 2], R[0, 0]))
            stats[(addr, gi)].append((os.path.basename(os.path.dirname(path)), s_, a, b, t_[1], rms, lname, lighterr, lightL, hasn))
print('# Exact poses of every Dreamcast mesh in the real frames (generated by tools/oracle/dc_mesh_poses.py)\n')
print('Per model group (a texture run of a model): number of fitted instances, scale, tilt about X and yaw about Y in degrees (axes X right, Y up, Z down the screen), model-origin height, worst residual (world units). Hierarchy parts include their node offset in the fit.\n')
print('| model | group | n | scale | tilt X | yaw Y values | height | worst rms | frames |\n|---|---|---|---|---|---|---|---|---|')
for (addr, gi), rows in sorted(stats.items()):
    sc = sorted(set(round(r[1], 3) for r in rows)); ti = sorted(set(round(r[2], 1) for r in rows)); ya = sorted(set(round(r[3], 1) for r in rows)); hh = sorted(set(round(r[4], 2) for r in rows))
    lists = ','.join(sorted(set(r[6] for r in rows))); le = [r for r in rows if r[7] is not None]
    if le:
        Ls = np.array([r[8] for r in le]); light = 'L=(%.4f,%.4f,%.4f) |L|=%.4f err %.5f' % (*Ls.mean(0), np.linalg.norm(Ls.mean(0)), max(r[7] for r in le))
    else: light = 'no normals in the model' if not rows[0][9] else 'too few lit vertices'
    print('| %s | %d | %s | %d | %s | %s | %s | %s | %.5f | %s | %s |' % (hex(addr), gi, lists, len(rows), ','.join(map(str, sc[:4])), ','.join(map(str, ti[:4])), ','.join(map(str, ya[:6])), ','.join(map(str, hh[:4])), max(r[5] for r in rows), light, ','.join(sorted(set(r[0] for r in rows))[:5])))
