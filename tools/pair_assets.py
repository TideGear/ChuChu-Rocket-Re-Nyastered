#!/usr/bin/env python3
"""Pair Dreamcast disc images with their mobile counterparts by pixel content and write docs/asset_pairs.md.

usage: pair_assets.py <assets dir (local/cache/assets)> <output .md> [min similarity, default 0.90]

Each disc image (dreamcast/prs_png and ENGLISH__* in dreamcast/png; menu sheets are stored transposed, so both orientations are tried) and each frame of every
mobile sheet in ret_all (rNNNN.tex.bin + frames.bin) is reduced to a 24 x 24 alpha-weighted grey fingerprint; a pair is the best cosine similarity above the
threshold with a compatible aspect ratio. Fingerprints ignore resolution, so the iPad HD, iPhone and Dreamcast art of the same piece line up; the score and the
size ratio say how close they are. It is a content pairing, not a proof of identity: check low scores by eye."""
import glob, os, struct, sys
import numpy as np
from PIL import Image

N = 24

def fingerprint(img):
    img = img.convert('RGBA')
    a = np.array(img.resize((N, N), Image.BILINEAR)).astype(np.float32)
    alpha = a[..., 3] / 255.0
    grey = (a[..., 0] * 0.3 + a[..., 1] * 0.59 + a[..., 2] * 0.11) / 255.0
    v = np.concatenate([(grey * alpha).ravel(), alpha.ravel()])
    v = v - v.mean()
    n = np.linalg.norm(v)
    return v / n if n > 1e-6 else None

def disc_images(assets):
    files = sorted(glob.glob(os.path.join(assets, 'dreamcast', 'prs_png', '*.png')))
    files += sorted(glob.glob(os.path.join(assets, 'dreamcast', 'png', 'ENGLISH__*.png')))
    for f in files:
        try: yield os.path.relpath(f, os.path.join(assets, 'dreamcast')).replace('\\', '/'), Image.open(f).convert('RGBA')
        except OSError: continue

def mobile_frames(assets):
    ret = os.path.join(assets, 'ret_all')
    for tex in sorted(glob.glob(os.path.join(ret, 'r*.tex.bin'))):
        base = tex[:-8]; name = os.path.basename(base)
        frames = base + '.frames.bin'
        if not os.path.isfile(frames): continue
        with open(tex, 'rb') as f:
            w, h = struct.unpack('<2I', f.read(8)); pixels = f.read(w * h * 4)
        if len(pixels) != w * h * 4: continue
        sheet = Image.frombytes('RGBA', (w, h), pixels)
        with open(frames, 'rb') as f:
            count, = struct.unpack('<I', f.read(4)); data = f.read()
        rec = (len(data) // count) if count else 0
        for i in range(count):
            if rec < 16: break
            u0, v0, u1, v1 = struct.unpack_from('<4f', data, i * rec)
            box = (round(u0 * w), round(v0 * h), round(u1 * w), round(v1 * h)) if max(u1, v1) <= 1.0001 else (int(u0), int(v0), int(u1), int(v1))
            if box[2] - box[0] < 8 or box[3] - box[1] < 8: continue
            yield f'{name}#{i}', sheet.crop(box)

def main(assets, out, threshold):
    mob = []
    for name, im in mobile_frames(assets):
        fp = fingerprint(im)
        if fp is not None: mob.append((name, im.size, fp))
    disc = []
    for name, im in disc_images(assets):
        for orient, t in (('', im), ('T', im.transpose(Image.Transpose.TRANSPOSE))):
            fp = fingerprint(t)
            if fp is not None: disc.append((name, orient, im.size, t.size, fp))
    if not mob or not disc:
        print('nothing to pair (mobile frames: %d, disc images: %d)' % (len(mob), len(disc))); return
    M = np.stack([m[2] for m in mob]); D = np.stack([d[4] for d in disc])
    sim = D @ M.T
    best = {}
    for i, d in enumerate(disc):
        order = np.argsort(-sim[i])[:3]
        for j in order:
            s = float(sim[i, j]); ratio = (d[3][0] / d[3][1]) / (mob[j][1][0] / mob[j][1][1])
            if s >= threshold and 0.8 <= ratio <= 1.25:
                key = d[0]
                if key not in best or s > best[key][0]:
                    best[key] = (s, d[1], d[2], mob[j][0], mob[j][1])
                break
    rows = sorted(best.items(), key=lambda kv: (-kv[1][0], kv[0]))
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# Dreamcast to mobile asset pairs\n\nGenerated by `tools/pair_assets.py` (content fingerprints, resolution independent; see the script header). '
                f'{len(rows)} of {len({d[0] for d in disc})} disc images found a mobile frame at similarity >= {threshold:.2f} and a compatible aspect ratio. '
                'Size ratio = mobile width / disc width. Check scores below 0.97 by eye. Regenerate whenever assets are decoded or matched, and add hand findings (what differs) in the notes column below.\n\n'
                '| Disc image | Orientation | Disc size | Mobile frame | Mobile size | Similarity | Size ratio |\n|---|---|---|---|---|---|---|\n')
        for name, (s, orient, dsz, mname, msz) in rows:
            f.write(f'| {name} | {orient or "as is"} | {dsz[0]}x{dsz[1]} | {mname} | {msz[0]}x{msz[1]} | {s:.3f} | {msz[0] / dsz[0]:.2f} |\n')
    print('wrote', out, len(rows), 'pairs;', len(mob), 'mobile frames;', len({d[0] for d in disc}), 'disc images')

if __name__ == '__main__':
    if len(sys.argv) < 3: raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2], float(sys.argv[3]) if len(sys.argv) > 3 else 0.90)
